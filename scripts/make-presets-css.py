"""Write shared/styles/presets.css (one body.nr_scheme_* block per preset) from scripts/presets.json."""
import json, os

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
PRESETS = {k: v for k, v in json.load(open(os.path.join(HERE, "presets.json"))).items() if not k.startswith("_")}
TOKENS = [("primary", "primary"), ("primary-dark", "primaryDark"), ("primary-soft", "primarySoft"),
          ("accent", "accent"), ("accent-dark", "accentDark"), ("accent-bright", "accentBright"),
          ("nav-active-bg", "navActiveBg"), ("nav-active-text", "navActiveText"), ("page-bg", "pageBg"),
          ("surface", "surface"), ("text", "text"), ("muted", "muted"), ("border", "border"),
          ("hero-position", "heroPosition")]


def rgb(h):
    return ",".join(str(int(h[i:i + 2], 16)) for i in (1, 3, 5))


def main():
    out = ["/**",
           " * NusantaraReborn — preset tokens. Generated by scripts/make-presets-css.py from",
           " * scripts/presets.json; edit those files instead. Contrast is checked by scripts/check-contrast.py.",
           " * Developed by Ikhwan Arief (ikhwan[at]unand.ac.id).",
           " * Copyright (c) 2026 Ikhwan Arief. Copyright held by the application developer.",
           " * Code license: GPL-3.0-or-later.",
           " */"]
    for name, p in PRESETS.items():
        out.append(f"body.nr_theme.nr_scheme_{name} {{")
        for css, key in TOKENS:
            out.append(f"    --nr-{css}: {p[key]};")
        out.append(f"    --nr-primary-dark-rgb: {rgb(p['primaryDark'])};")
        out.append(f'    --nr-ornament: url("../assets/ornaments/{name}.svg");')
        out.append("}")
    path = os.path.join(ROOT, "shared", "styles", "presets.css")
    with open(path, "w") as f:
        f.write("\n".join(out) + "\n")
    print("wrote", path)


if __name__ == "__main__":
    main()
